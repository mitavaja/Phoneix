import mongoose from "mongoose";

const couponCategorySchema = new mongoose.Schema(
  {
    name: {
      type: String,
      required: true,
      unique: true,
      trim: true,
    },
    description: {
      type: String,
      default: "",
      trim: true,
    },
    isActive: {
      type: Boolean,
      default: true,
    },
  },
  {
    timestamps: true,
  }
);

const CouponCategory = mongoose.model("CouponCategory", couponCategorySchema);
export default CouponCategory;
